// Not in @types/node yet; Node 22.19+ and 24.5+
type CaApi = {
  getCACertificates?: (type: "default") => string[];
  setDefaultCACertificates?: (certs: string[]) => void;
};

/** Adds the cross-signed Root YR to the CA list fetch and WebSocket use by default. */
export function trustPlexDirectChain() {
  const api = tls as unknown as CaApi;
  if (!api.getCACertificates || !api.setDefaultCACertificates) {
    console.warn(
      `Node ${process.version} can't extend its CA list; plex.direct addresses may fail certificate checks. Use Node 22.19 or newer.`
    );
    return;
  }
  api.setDefaultCACertificates([...api.getCACertificates("default"), ROOT_YR_X1_CROSS]);
}
